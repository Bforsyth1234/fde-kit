"""Generate the committed replay fixtures under `evals/runs/`.

    python -m evals.make_replay_fixtures              # rewrite evals/runs/replay-*.jsonl
    python -m evals.make_replay_fixtures --out DIR    # write them somewhere else (tests)

Each fixture is a real run: a `MockProvider` with a fixed script, the builtin tool registry, and
`Agent.run(prompt, record=path)` streaming the rows exactly as the agent writes them. The
`replay-*` cases in `evals/golden.jsonl` replay these files, so they must be byte-identical from
one generation to the next: `tests/test_evals.py` regenerates them into a temp dir and compares
bytes, which is how a drift in the record format gets caught.

Three things in a run file vary between runs, and each is pinned here:

- `run_id`: `fde_kit.agent` imports `new_run_id` by name, so it is stubbed on the agent module
  (patching `fde_kit.record` would not reach it);
- `created_at`: same, via `utc_now`;
- the result row's `total_ms`: wall-clock, rewritten to 0 after the file is closed. Mock LLM rows
  carry fixed token counts and no latency, and tool rows have no timing, so nothing else moves.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from fde_kit import agent as agent_module
from fde_kit.agent import Agent
from fde_kit.builtin_tools import registry
from fde_kit.config import Settings
from fde_kit.llm import MockProvider
from fde_kit.prompts import PACKAGED

RUNS_DIR = Path(__file__).resolve().parent / "runs"
CREATED_AT = "2026-10-22T00:00:00Z"
# Every header field is pinned explicitly (and `.env` ignored) so a developer's FDE_* overrides
# or a local ./prompts directory cannot change the generated bytes.
SETTINGS = Settings(
    _env_file=None,
    provider="mock",
    otel_enabled=False,
    max_turns=10,
    max_tokens=2048,
    prompt="default",
    prompts_dir=str(PACKAGED),
    system_prompt=None,
)


@dataclass
class Fixture:
    name: str
    run_id: str
    prompt: str
    script: list[str | dict[str, Any]]
    edit: Callable[[list[dict[str, Any]]], None] | None = field(default=None)
    """Applied to the parsed rows after recording; how a 'broken' record is made reproducibly."""


def _edit_tool_input_to_warranty(rows: list[dict[str, Any]]) -> None:
    # replay-03: the model's recorded tool call still asks for `sla`, but the tool row now says
    # the tool ran for `warranty`. On replay, ReplayRegistry compares (name, input) of the call
    # against the next tool row, finds `sla != warranty`, and raises ReplayDiverged, which the
    # agent reports as stopped_reason="replay_diverged".
    tool_rows = [r for r in rows if r["kind"] == "tool"]
    assert len(tool_rows) == 1 and tool_rows[0]["input"] == {"topic": "sla"}
    tool_rows[0]["input"] = {"topic": "warranty"}


FIXTURES: list[Fixture] = [
    Fixture(
        name="replay-01",
        run_id="r-replay000001",
        prompt="What is the uptime SLA? Cite your source.",
        script=[
            {"tool_calls": [{"name": "lookup_policy", "input": {"topic": "sla"}}]},
            "The uptime SLA is 99.9% monthly, measured on the API gateway [1].",
        ],
    ),
    Fixture(
        name="replay-02",
        run_id="r-replay000002",
        prompt=(
            "How long is data retained after a contract ends, and what is the refund window? "
            "Cite sources."
        ),
        script=[
            {
                "tool_calls": [
                    {"name": "lookup_policy", "input": {"topic": "data retention"}},
                    {"name": "lookup_policy", "input": {"topic": "refund policy"}},
                ]
            },
            "Customer data is retained for 90 days after termination [1], and refunds are "
            "issued within 30 days of purchase [2].",
        ],
    ),
    Fixture(
        name="replay-03",
        run_id="r-replay000003",
        prompt="What is the uptime SLA? Cite your source.",
        script=[
            {"tool_calls": [{"name": "lookup_policy", "input": {"topic": "sla"}}]},
            "The uptime SLA is 99.9% monthly, measured on the API gateway [1].",
        ],
        edit=_edit_tool_input_to_warranty,
    ),
]


@contextmanager
def _pinned(run_id: str) -> Iterator[None]:
    """Fix `run_id` and `created_at` for one recording, restoring the real functions after."""
    orig_id, orig_now = agent_module.new_run_id, agent_module.utc_now
    agent_module.new_run_id = lambda: run_id
    agent_module.utc_now = lambda: CREATED_AT
    try:
        yield
    finally:
        agent_module.new_run_id, agent_module.utc_now = orig_id, orig_now


def _dumps(row: dict[str, Any]) -> str:
    # Same serialisation as fde_kit.record._dumps: `kind` is already first in parsed rows.
    return json.dumps(row, ensure_ascii=False, default=str)


def write_fixture(fx: Fixture, out_dir: Path) -> Path:
    path = out_dir / f"{fx.name}.jsonl"
    with _pinned(fx.run_id):
        agent = Agent(registry, provider=MockProvider(fx.script), settings=SETTINGS)
        result = agent.run(fx.prompt, record=path)
    if result.stopped_reason != "end_turn":
        raise RuntimeError(f"{fx.name}: recording stopped with {result.stopped_reason!r}")

    rows = [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    rows[-1]["total_ms"] = 0  # wall-clock; the only timing field in the file
    if fx.edit is not None:
        fx.edit(rows)
    path.write_text("".join(_dumps(r) + "\n" for r in rows), encoding="utf-8")
    return path


def generate(out_dir: Path = RUNS_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    return [write_fixture(fx, out_dir) for fx in FIXTURES]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="regenerate evals/runs/replay-*.jsonl")
    p.add_argument("--out", type=Path, default=RUNS_DIR)
    args = p.parse_args(argv)
    for path in generate(args.out):
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
