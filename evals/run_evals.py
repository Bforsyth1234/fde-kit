"""Run the golden set through the agent and gate on pass rate.

    python -m evals.run_evals                     # real model, threshold from settings
    python -m evals.run_evals --provider mock     # offline: replays each case's scripted mock
    python -m evals.run_evals --limit 5 --json out.json
    python -m evals.run_evals --set rag --provider mock   # the lease-corpus set, tools for real
    python -m evals.run_evals --set edgar --seed --provider mock   # SEC filings, seeded offline

Exit code is 0 when pass rate >= threshold, 1 otherwise. That exit code is the CI gate.

Three sets. `--set golden` (the default, evals/golden.jsonl) runs against the builtin tools and
needs nothing but Python. `--set rag` (evals/golden_rag.jsonl) runs over the seeded demo lease
corpus: each case carries a `tenant`, and the agent gets `tenant_search_registry` for that tenant
from one `TenantStore` opened for the whole run (settings `rag_url`, else the app role derived
from `rag_admin_url`; embedder from `--embedder` or settings `rag_embedder`). Seed first with
`fde rag seed-demo`. In mock mode the script drives the *model*, but `search_documents`,
`query_table` and `fetch_document` run for real against Postgres, so a rag mock run is a
tools+harness check: it proves the SQL and queries in the script return what the scripted answer
cites, under RLS, with the citations resolving to real Sources. The live-model run is the model
check.

`--set edgar` (evals/golden_edgar.jsonl) is the same shape over the pinned SEC EDGAR corpus in
tenants `pharma-a` / `pharma-b` (FY2019-FY2021 10-Ks, real restatements and rounded repeats).
`--seed` first seeds those tenants from the committed offline fixtures
(`seed_edgar_offline`: no network, no contact string); it is idempotent, so re-running it writes
nothing new.

Mock mode exists to test the *harness*, not the model: each case ships a `mock` script that the
MockProvider replays. If a case passes in mock mode and fails against the real model, the model
is the problem; if it fails in both, the check or the tool is.

A case may instead (or additionally) carry `"replay": "evals/runs/<file>.jsonl"`: a recorded run
(see `fde_kit.record`, generated by `python -m evals.make_replay_fixtures`) that is replayed
exactly, LLM rows and tool rows alike. Replay cases are a harness check too, so they replay the
record even when `--provider anthropic` is chosen: they prove record/replay round-trips, not the
model.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

from rich.console import Console
from rich.table import Table

from fde_kit.agent import Agent
from fde_kit.builtin_tools import registry
from fde_kit.config import Settings, get_settings
from fde_kit.llm import LLMProvider, MockProvider, make_provider
from fde_kit.record import RunRecord, recorded_prompt, replay_session
from fde_kit.tools import ToolRegistry
from fde_kit.tracing import init_tracing

from .scorers import SCORERS, JudgeContext

REPO_ROOT = Path(__file__).resolve().parent.parent
GOLDEN = Path(__file__).parent / "golden.jsonl"
GOLDEN_RAG = Path(__file__).parent / "golden_rag.jsonl"
GOLDEN_EDGAR = Path(__file__).parent / "golden_edgar.jsonl"
SETS: dict[str, Path] = {"golden": GOLDEN, "rag": GOLDEN_RAG, "edgar": GOLDEN_EDGAR}
EDGAR_TENANTS: dict[str, str] = {
    "pharma-a": "Pharma A (Pfizer, Gilead, Vertex)",
    "pharma-b": "Pharma B (Moderna, Regeneron)",
}
"""The EDGAR eval tenants; their filings are pinned in `rag/adapters/edgar_manifest.json`."""
EDGAR_FIXTURES = REPO_ROOT / "evals" / "fixtures" / "edgar" / "cache"
console = Console()

_rag_store: Any = None
"""The run's `TenantStore`, opened by `open_rag_store` on first use and shared by every case."""


def open_rag_store(settings: Settings | None = None, embedder: str | None = None) -> Any:
    """Open (once) the store that rag cases build their tenant registries from.

    Connection: settings `rag_url` when set, else the app role derived from `rag_admin_url`
    (what `fde rag` does). Embedder: `embedder`, else settings `rag_embedder`. Repeated calls
    return the same store; `close_rag_store()` drops it so a test can reopen with other env.
    """
    global _rag_store
    if _rag_store is None:
        from fde_kit.rag import TenantStore, app_url_from_admin, make_embedder

        settings = settings or get_settings()
        url = settings.rag_url or app_url_from_admin(settings.rag_admin_url)
        _rag_store = TenantStore(url, make_embedder(embedder or settings.rag_embedder))
    return _rag_store


def close_rag_store() -> None:
    global _rag_store
    if _rag_store is not None:
        _rag_store.close()
        _rag_store = None


def known_tenants() -> set[str]:
    """Tenants a case may name: the demo lease tenants plus the EDGAR tenants."""
    from fde_kit.rag.demo_corpus import TENANTS

    return set(TENANTS) | set(EDGAR_TENANTS)


def seed_edgar_offline(
    admin_url: str | None = None, store: Any = None, cache_dir: Path = EDGAR_FIXTURES
) -> dict[str, Any]:
    """Migrate, create `pharma-a` / `pharma-b`, and ingest each tenant's pinned filings from
    the offline fixture cache. No network and no contact string: an offline client serves
    only from `cache_dir`. Idempotent (ingest skips unchanged documents). `store` defaults to
    the run's store (`open_rag_store`). Returns the IngestReport per tenant."""
    from fde_kit.rag import create_tenant, migrate
    from fde_kit.rag.adapters import EdgarAdapter, EdgarClient, filings_for, ingest

    admin_url = admin_url or get_settings().rag_admin_url
    migrate(admin_url)
    store = store if store is not None else open_rag_store()
    client = EdgarClient("", cache_dir=cache_dir, offline=True)
    reports: dict[str, Any] = {}
    for tid, name in EDGAR_TENANTS.items():
        create_tenant(admin_url, tid, name)
        with store.session(tid) as s:
            reports[tid] = ingest(s, EdgarAdapter(client, filings_for(tid)))
    return reports


def case_registry(case: dict[str, Any]) -> ToolRegistry:
    """The builtin registry, or for a case with a `tenant` the three retrieval tools bound to
    that tenant. The tenant comes from the case file, never from the model or the prompt."""
    if "tenant" not in case:
        return registry
    from fde_kit.rag import tenant_search_registry

    tenant = case["tenant"]
    if tenant not in known_tenants():  # load_cases checks too; this guards hand-built cases
        raise ValueError(
            f"{case['id']}: unknown tenant {tenant!r}, not in {sorted(known_tenants())}"
        )
    return tenant_search_registry(open_rag_store(), tenant)


@dataclass
class CaseResult:
    id: str
    category: str
    passed: bool
    output: str
    tools_called: list[str]
    turns: int
    latency_ms: float
    input_tokens: int
    output_tokens: int
    details: list[str]
    model: str = ""
    prompt_name: str = ""
    prompt_sha256: str = ""
    sources: int = 0
    cited: int = 0
    fabricated_citations: int = 0
    replay: str = ""
    """The run file this case replayed (repo-relative), empty for scripted mock cases."""


def replay_path(case: dict[str, Any]) -> Path:
    """`case["replay"]` resolved against the repo root, so it works from any cwd."""
    return REPO_ROOT / case["replay"]


def load_cases(
    path: Path = GOLDEN, limit: int | None = None, ids: set[str] | None = None
) -> list[dict[str, Any]]:
    cases = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    for c in cases:
        for key in ("id", "prompt", "checks"):
            if key not in c:
                raise ValueError(f"golden case missing '{key}': {c}")
        for chk in c["checks"]:
            if chk["type"] not in SCORERS:
                raise ValueError(f"{c['id']}: unknown check type {chk['type']!r}")
        if "mock" not in c and "replay" not in c:
            raise ValueError(f"{c['id']}: needs a 'mock' script or a 'replay' run file")
        if "replay" in c and not replay_path(c).is_file():
            raise ValueError(f"{c['id']}: replay file not found: {replay_path(c)}")
        if "tenant" in c and c["tenant"] not in known_tenants():
            raise ValueError(
                f"{c['id']}: unknown tenant {c['tenant']!r}; rag cases run over the demo "
                f"lease corpus or the EDGAR corpus, tenants {sorted(known_tenants())}"
            )
    if ids:
        missing = ids - {c["id"] for c in cases}
        if missing:
            raise ValueError(f"unknown case ids: {sorted(missing)}")
        cases = [c for c in cases if c["id"] in ids]
    return cases[:limit] if limit else cases


def run_case(case: dict[str, Any], provider_name: str, judge: LLMProvider | None) -> CaseResult:
    settings = get_settings()
    t0 = time.perf_counter()
    reg = case_registry(case)
    if "replay" in case:
        # Exact replay of a recorded run, whatever --provider says: the recorded LLM rows are the
        # model, so this checks the record/replay harness, never the live model. The agent gets
        # the record's pinned system prompt so the header it would write matches the parent.
        rec = RunRecord.load(replay_path(case))
        session = replay_session(rec, reg)
        agent = Agent(
            reg,
            provider=session.provider,
            settings=settings,
            system_prompt=rec.header["prompt_text"],
        )
        result = agent.run(recorded_prompt(rec), session=session)
    else:
        if provider_name == "mock":
            provider: LLMProvider = MockProvider(case.get("mock", []))
        else:
            provider = make_provider(
                provider_name,
                settings.model,
                api_key=settings.anthropic_api_key,
                workspace_id=settings.anthropic_workspace_id,
            )
        # Mock or live, the tools are real: for a rag case they hit Postgres under RLS.
        agent = Agent(reg, provider=provider, settings=settings)
        result = agent.run(case["prompt"])
    latency = (time.perf_counter() - t0) * 1000

    ctx = JudgeContext(provider=judge, prompt=case["prompt"])
    details: list[str] = []
    passed = True
    for chk in case["checks"]:
        outcome = SCORERS[chk["type"]](result, chk.get("value"), ctx)
        details.append(("PASS " if outcome.passed else "FAIL ") + outcome.detail)
        passed = passed and outcome.passed

    return CaseResult(
        id=case["id"],
        category=case.get("category", ""),
        passed=passed,
        output=result.output,
        tools_called=result.tools_called,
        turns=result.turns,
        latency_ms=latency,
        input_tokens=result.usage.input_tokens,
        output_tokens=result.usage.output_tokens,
        details=details,
        model=result.model,
        prompt_name=result.prompt_name,
        prompt_sha256=result.prompt_sha256,
        sources=len(result.sources),
        cited=len(result.cited),
        fabricated_citations=len(result.fabricated_citations),
        replay=case.get("replay", ""),
    )


def summarise(results: list[CaseResult]) -> dict[str, Any]:
    by_cat: dict[str, list[CaseResult]] = defaultdict(list)
    for r in results:
        by_cat[r.category].append(r)
    cited = sum(r.cited for r in results)
    fabricated = sum(r.fabricated_citations for r in results)
    return {
        "model": results[0].model if results else "",
        "prompt_name": results[0].prompt_name if results else "",
        "prompt_sha256": results[0].prompt_sha256 if results else "",
        # Of the citations the answers made, how many pointed at a Source a tool returned.
        # 1.0 or there is a fabricated citation somewhere; see fabricated_citations per case.
        "citation_precision": (cited / (cited + fabricated)) if (cited + fabricated) else 1.0,
        "fabricated_citations": fabricated,
        "total": len(results),
        "passed": sum(r.passed for r in results),
        "pass_rate": (sum(r.passed for r in results) / len(results)) if results else 0.0,
        "p50_latency_ms": _percentile([r.latency_ms for r in results], 50),
        "p95_latency_ms": _percentile([r.latency_ms for r in results], 95),
        "input_tokens": sum(r.input_tokens for r in results),
        "output_tokens": sum(r.output_tokens for r in results),
        "by_category": {
            cat: {"total": len(rs), "passed": sum(r.passed for r in rs)}
            for cat, rs in sorted(by_cat.items())
        },
    }


def _percentile(values: list[float], pct: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    k = max(0, min(len(s) - 1, round((pct / 100) * (len(s) - 1))))
    return s[k]


def print_report(
    results: list[CaseResult], summary: dict[str, Any], threshold: float, set_name: str = "golden"
) -> None:
    title = f"eval results ({set_name})"
    if summary.get("prompt_sha256"):
        title += (
            f"  ·  model {summary['model']}  ·  prompt "
            f"{summary['prompt_name']}@{summary['prompt_sha256'][:12]}"
        )
    table = Table(title=title, show_lines=False)
    table.add_column("id")
    table.add_column("cat")
    table.add_column("ok", justify="center")
    table.add_column("tools")
    table.add_column("turns", justify="right")
    table.add_column("ms", justify="right")
    table.add_column("failing checks")
    for r in results:
        fails = "; ".join(d for d in r.details if d.startswith("FAIL"))
        table.add_row(
            r.id,
            r.category,
            "[green]✓[/]" if r.passed else "[red]✗[/]",
            ",".join(r.tools_called) or "-",
            str(r.turns),
            f"{r.latency_ms:.0f}",
            fails,
        )
    console.print(table)

    cat_line = "  ".join(
        f"{c}={v['passed']}/{v['total']}" for c, v in summary["by_category"].items()
    )
    console.print(cat_line)
    verdict = "PASS" if summary["pass_rate"] >= threshold else "FAIL"
    color = "green" if verdict == "PASS" else "red"
    console.print(
        f"[{color} bold]{verdict}[/] {summary['passed']}/{summary['total']} "
        f"({summary['pass_rate']:.0%}) threshold {threshold:.0%} | "
        f"p50 {summary['p50_latency_ms']:.0f} ms, p95 {summary['p95_latency_ms']:.0f} ms | "
        f"tokens {summary['input_tokens']} in / {summary['output_tokens']} out"
    )
    if summary["fabricated_citations"]:
        console.print(
            f"[red bold]fabricated citations: {summary['fabricated_citations']}[/] "
            f"(citation precision {summary['citation_precision']:.2f})"
        )


def main(argv: list[str] | None = None) -> int:
    settings = get_settings()
    p = argparse.ArgumentParser(description="fde-kit eval runner")
    p.add_argument("--provider", default=settings.provider, choices=["anthropic", "mock"])
    p.add_argument("--threshold", type=float, default=settings.eval_pass_threshold)
    p.add_argument("--limit", type=int)
    p.add_argument("--ids", help="comma-separated case ids to run, e.g. calc-02,notool-01")
    p.add_argument(
        "--set",
        default="golden",
        choices=sorted(SETS),
        help="golden: builtin tools, offline; rag: lease corpus, needs a seeded Postgres; "
        "edgar: SEC filings in pharma-a/pharma-b, needs Postgres (seed with --seed)",
    )
    p.add_argument(
        "--seed",
        action="store_true",
        help="edgar set: first seed pharma-a/pharma-b from the offline fixtures (idempotent)",
    )
    p.add_argument("--golden", type=Path, help="a case file; overrides --set's file")
    p.add_argument(
        "--embedder", help="rag/edgar sets only: 'hash' or 'bge'; default from FDE_RAG_EMBEDDER"
    )
    p.add_argument("--json", type=Path, help="write full results to this file")
    p.add_argument(
        "--no-judge", action="store_true", help="skip LLM-as-judge checks even with a real provider"
    )
    args = p.parse_args(argv)

    # Mock runs are a harness self-check; there is nothing worth tracing and no collector
    # is expected to be running.
    if args.provider != "mock":
        init_tracing(settings)
    ids = {i.strip() for i in args.ids.split(",") if i.strip()} if args.ids else None
    cases = load_cases(args.golden or SETS[args.set], args.limit, ids)
    if args.seed:
        # Migrates first, so on a fresh database the app role exists before the store opens.
        from fde_kit.rag import migrate

        migrate(settings.rag_admin_url)
        store = open_rag_store(settings, args.embedder)
        for tid, rep in seed_edgar_offline(settings.rag_admin_url, store).items():
            console.print(
                f"seeded {tid}: {rep.documents_changed}/{rep.documents} documents written, "
                f"{rep.facts} facts, {rep.conflict_groups} conflict groups"
            )
    if args.set in ("rag", "edgar") or any("tenant" in c for c in cases):
        open_rag_store(settings, args.embedder)

    judge: LLMProvider | None = None
    if args.provider != "mock" and not args.no_judge:
        judge = make_provider(
            args.provider,
            settings.model,
            api_key=settings.anthropic_api_key,
            workspace_id=settings.anthropic_workspace_id,
        )

    try:
        results = [run_case(c, args.provider, judge) for c in cases]
    finally:
        close_rag_store()
    summary = summarise(results)
    print_report(results, summary, args.threshold, args.set)

    if args.json:
        args.json.write_text(
            json.dumps(
                {"summary": summary, "results": [asdict(r) for r in results]}, indent=2
            )
        )
        console.print(f"wrote {args.json}")

    return 0 if summary["pass_rate"] >= args.threshold else 1


if __name__ == "__main__":
    sys.exit(main())
